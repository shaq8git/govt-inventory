class Command(BaseCommand):
    help = "Apply purchase and sales rates to existing products (skips products that already have rates)"

    def handle(self, *args, **options):
        product_map = {_nfc("NFC", p.productname): p for p in Product.objects.all()}
        updated = 0
        skipped = 0
        not_found = 0

        for pname, purrate, salesrate in RATES:
            key = _nfc("NFC", pname)
            prod = product_map.get(key)
            if prod is None:
                self.stdout.write(self.style.WARNING(f"  Not found: {pname}"))
                not_found += 1
                continue
            if prod.purchaserate != 0 or prod.salesrate != 0:
                skipped += 1
                continue
            prod.purchaserate = Decimal(purrate)
            prod.salesrate = Decimal(salesrate)
            prod.save(update_fields=["purchaserate", "salesrate"])
            self.stdout.write(f"  {prod.prodcode}  {prod.productname}  →  pur={purrate}  sal={salesrate}")
            updated += 1

        self.stdout.write(
            self.style.SUCCESS(
                f"\nDone. {updated} updated, {skipped} already had rates, {not_found} not found."
            )
        )
