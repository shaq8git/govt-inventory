class Command(BaseCommand):
    help = "Seed circleoffice and designation tables from SQL data"

    def handle(self, *args, **options):
        self._seed_circleoffice()
        self._seed_designation()

    def _seed_circleoffice(self):
        created = 0
        for pk, name, address, headoffice_id, slno in CIRCLE_OFFICES:
            _, made = CircleOffice.objects.update_or_create(
                id=pk,
                defaults={
                    "circleofficename": name,
                    "officeaddress": address,
                    "headoffice_id": headoffice_id,
                    "slno": slno,
                },
            )
            if made:
                created += 1
        self.stdout.write(self.style.SUCCESS(
            f"CircleOffice: {created} created, {len(CIRCLE_OFFICES) - created} already existed"
        ))

    def _seed_designation(self):
        created = 0
        for pk, name, cls, grade_id, nopost, desigslno, officerornot_id in DESIGNATIONS:
            _, made = Designation.objects.update_or_create(
                id=pk,
                defaults={
                    "designationname": name,
                    "class_field": cls,
                    "grade_id": grade_id,
                    "nopost": nopost,
                    "desigslno": desigslno,
                    "officerornot_id": officerornot_id,
                },
            )
            if made:
                created += 1
        self.stdout.write(self.style.SUCCESS(
            f"Designation: {created} created, {len(DESIGNATIONS) - created} already existed"
        ))
