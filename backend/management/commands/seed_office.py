class Command(BaseCommand):
    help = "Seed office table from SQL data"

    def handle(self, *args, **options):
        do_map = {do.id: do for do in DistrictOffice.objects.all()}
        created = updated = 0
        for pk, do_id, name, address, activity, orderno in OFFICES:
            do = do_map.get(do_id)
            if do is None:
                self.stdout.write(self.style.WARNING(
                    f"DistrictOffice id={do_id} not found, skipping office id={pk}"
                ))
                continue
            _, made = Office.objects.update_or_create(
                id=pk,
                defaults={
                    "districtoffice": do,
                    "officename": name,
                    "officeaddress": address,
                    "activity": activity,
                    "orderno": orderno,
                },
            )
            if made:
                created += 1
            else:
                updated += 1
        self.stdout.write(self.style.SUCCESS(
            f"Office: {created} created, {updated} updated"
        ))
